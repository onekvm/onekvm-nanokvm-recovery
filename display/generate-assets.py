"""Regenerate Pro recovery artwork; OE and the device use the checked-in header."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
BACKGROUND = (8, 11, 17)
TEXT = (244, 244, 245)
MUTED = (161, 161, 170)
FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")


def rgb565(pixel):
    r, g, b = pixel
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def label(image, text, size, xy, color, centered=False):
    font = ImageFont.truetype(str(FONT_DIR / "DejaVuSans.ttf"), size)
    left, top, right, bottom = font.getbbox(text)
    x, y = xy
    if centered:
        x -= (right - left) // 2
        y -= (bottom - top) // 2
    ImageDraw.Draw(image).text((x - left, y - top), text, font=font, fill=color)


# Match the initialization screen: wordmark on the left, addresses on the
# right, and a blue mode label below. No action arrow: this is a status screen.
image = Image.new("RGB", (320, 172), BACKGROUND)
logo = Image.open(HERE / "logo.png").convert("RGBA")
logo = logo.crop(logo.getbbox())
logo = logo.resize((120, round(120 * logo.height / logo.width)), Image.Resampling.LANCZOS)
image.paste(logo, (12, (112 - logo.height) // 2), logo)
label(image, "Open in browser", 11, (148, 10), MUTED)
ImageDraw.Draw(image).rounded_rectangle((12, 112, 307, 159), radius=24, fill=(22, 119, 255))
label(image, "Recovery mode", 16, (160, 136), TEXT, centered=True)

runs = []
for pixel in image.getdata():
    color = rgb565(pixel)
    if runs and runs[-1][1] == color and runs[-1][0] < 65535:
        runs[-1][0] += 1
    else:
        runs.append([1, color])

header = [
    "/* SPDX-License-Identifier: MIT */",
    "/* Generated by display/generate-assets.py; RGB565 RLE and alpha glyphs. */",
    "static const uint16_t recovery_pro_background[] = {",
]
for offset in range(0, len(runs), 6):
    header.append("    " + ", ".join(f"{n}, 0x{c:04x}" for n, c in runs[offset:offset + 6]) + ",")
header.append("};")

font = ImageFont.truetype(str(FONT_DIR / "DejaVuSansMono.ttf"), 15)
header.append("enum { RECOVERY_IP_WIDTH = 9, RECOVERY_IP_HEIGHT = 20 };")
header.append("static const uint8_t recovery_ip_glyphs[11][RECOVERY_IP_WIDTH * RECOVERY_IP_HEIGHT] = {")
for ch in "0123456789.":
    glyph = Image.new("L", (9, 20))
    ImageDraw.Draw(glyph).text((0, 0), ch, font=font, fill=255)
    data = list(glyph.getdata())
    header.append("    {")
    for offset in range(0, len(data), 18):
        header.append("        " + ", ".join(str(value) for value in data[offset:offset + 18]) + ",")
    header.append("    },")
header.append("};")

waiting = Image.new("RGB", (160, 20), BACKGROUND)
label(waiting, "Waiting for network", 13, (0, 3), MUTED)
header.append("static const uint16_t recovery_pro_waiting[160 * 20] = {")
data = [rgb565(pixel) for pixel in waiting.getdata()]
for offset in range(0, len(data), 12):
    header.append("    " + ", ".join(f"0x{color:04x}" for color in data[offset:offset + 12]) + ",")
header.append("};")
(HERE / "assets.h").write_text("\n".join(header) + "\n")

# This preview is optional development output, never a build input.
if __name__ == "__main__":
    print(f"Wrote {HERE / 'assets.h'}")
